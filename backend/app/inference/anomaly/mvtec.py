"""MVTec normal-only patch-bank inference, faithfully ported from notebook cell 7.

Reference: notebooks/defectspot.ipynb, cell 7 (GitHub commit main on 2026-10-28).
Never convert uncalibrated distances to a binary quality verdict.
Only load local, trusted joblib files: deserialization can execute code.
"""
from __future__ import annotations

import base64
import io
import math
import time
from functools import lru_cache
from pathlib import Path

import cv2
import joblib
import numpy as np
from PIL import Image, ImageOps

PROJECT_ROOT = Path(__file__).resolve().parents[4]
MODEL_DIR = PROJECT_ROOT / "models"
CATEGORIES = (
    "bottle", "cable", "capsule", "carpet", "grid", "hazelnut", "leather",
    "metal_nut", "pill", "screw", "tile", "toothbrush", "transistor", "wood", "zipper",
)


def patch_features(rgb: np.ndarray, side: int = 128, grid: int = 16) -> np.ndarray:
    """Exact descriptors and operation order from Day 22 notebook's patch_features()."""
    a = cv2.resize(rgb, (side, side), interpolation=cv2.INTER_AREA)
    lab = cv2.cvtColor(a, cv2.COLOR_RGB2LAB).astype(np.float32) / 255
    gray = cv2.cvtColor(a, cv2.COLOR_RGB2GRAY).astype(np.float32) / 255
    sx = cv2.Sobel(gray, cv2.CV_32F, 1, 0, ksize=3)
    sy = cv2.Sobel(gray, cv2.CV_32F, 0, 1, ksize=3)
    mag = cv2.magnitude(sx, sy)
    edge = cv2.Laplacian(gray, cv2.CV_32F)
    size = side // grid
    feats = []
    for y in range(grid):
        for x in range(grid):
            ys = slice(y * size, (y + 1) * size)
            xs = slice(x * size, (x + 1) * size)
            q = lab[ys, xs].reshape(-1, 3)
            g, m, e = gray[ys, xs], mag[ys, xs], edge[ys, xs]
            feats.append(np.r_[
                q.mean(axis=0), q.std(axis=0), g.mean(), g.std(),
                m.mean(), m.std(), np.abs(e).mean(), np.percentile(g, [10, 50, 90]),
            ])
    return np.asarray(feats, dtype=np.float32)


@lru_cache(maxsize=15)
def load_bank(category: str):
    if category not in CATEGORIES:
        raise ValueError("Unsupported MVTec category")
    path = MODEL_DIR / f"mvtec_patch_{category}.joblib"
    if not path.is_file():
        raise FileNotFoundError(f"MVTec bank missing: {path}")
    # Only run with known/trusted files generated by your Kaggle notebook.
    payload = joblib.load(path)
    if not isinstance(payload, dict) or not {"nn", "mu", "sigma", "resize", "grid", "category"} <= payload.keys():
        raise ValueError("Invalid patch-bank schema")
    if payload["category"] != category:
        raise ValueError("Patch-bank category mismatch")
    side, grid = int(payload["resize"]), int(payload["grid"])
    if side != 128 or grid != 16 or side % grid:
        raise ValueError(f"Unexpected training preprocessing: resize={side}, grid={grid}")
    mu = np.asarray(payload["mu"], dtype=np.float32)
    sigma = np.asarray(payload["sigma"], dtype=np.float32)
    if mu.shape != (14,) or sigma.shape != (14,) or np.any(sigma <= 0):
        raise ValueError("Incompatible bank feature normalization")
    nn = payload["nn"]
    if not hasattr(nn, "kneighbors") or getattr(nn, "n_features_in_", 14) != 14:
        raise ValueError("Incompatible nearest-neighbor estimator")
    return nn, mu, sigma, side, grid


def _jpg_base64(image: Image.Image) -> str:
    buffer = io.BytesIO()
    image.save(buffer, format="JPEG", quality=87)
    return base64.b64encode(buffer.getvalue()).decode("ascii")


def predict_mvtec(image: Image.Image, category: str, *, with_overlay: bool = True) -> dict:
    nn, mu, sigma, side, grid = load_bank(category)
    t0 = time.perf_counter()
    rgb = np.asarray(image.convert("RGB"))
    f = patch_features(rgb, side=side, grid=grid)
    # Same formula as notebook score_image(): raw distances in normalized 14D features.
    distances = nn.kneighbors((f - mu) / sigma, return_distance=True)[0][:, 0]
    if len(distances) != grid * grid or not np.isfinite(distances).all():
        raise ValueError("Invalid patch distances from bank")
    k = max(1, int(np.ceil(0.05 * len(distances))))
    image_score = float(np.sort(distances)[-k:].mean())
    scoremap = distances.reshape(grid, grid)
    elapsed_ms = round((time.perf_counter() - t0) * 1000, 2)

    result = {
        "pipeline": "mvtec_anomaly", "category": category,
        "model": f"mvtec_patch_{category}.joblib",
        "image": {"width": image.width, "height": image.height},
        "anomaly_score_raw": round(image_score, 6),
        "heatmap_grid": [grid, grid],
        "patch_distances": np.round(scoremap, 6).tolist(),
        "inference_ms": elapsed_ms,
        "decision": "not_assessed", "requires_human_review": True,
        "note": "Uncalibrated raw nearest-neighbor distance; larger usually means more anomalous within this category. Not a defect probability, not a pass/fail verdict. Heatmap is coarse 16x16.",
        "overlay_jpeg_base64": None,
    }
    if with_overlay:
        # Display-only scaling PER IMAGE; not a calibrated color bar across images.
        lo, hi = float(scoremap.min()), float(scoremap.max())
        normalized = np.zeros_like(scoremap, dtype=np.uint8) if hi <= lo else np.uint8(np.clip((scoremap - lo) / (hi - lo) * 255, 0, 255))
        heat = cv2.applyColorMap(normalized, cv2.COLORMAP_TURBO)
        heat = cv2.cvtColor(heat, cv2.COLOR_BGR2RGB)
        heat = cv2.resize(heat, image.size, interpolation=cv2.INTER_LINEAR)
        overlay = Image.blend(image.convert("RGB"), Image.fromarray(heat), alpha=0.40)
        result["overlay_jpeg_base64"] = _jpg_base64(overlay)
    return result
